package sandbox

import (
	"github.com/google/jsonschema-go/jsonschema"
)

// falseSchema represents `additionalProperties: false` in jsonschema-go. It
// enforces the strict, closed input schema required by SPEC §7.4 (S08).
//
// A fresh instance is returned per call: the schema is resolved as a tree by
// jsonschema-go, so a single shared instance reused in multiple places (e.g.
// top-level plus nested object items) would make the schema a graph and fail
// client-side resolution with "schemas ... do not form a tree".
func falseSchema() *jsonschema.Schema {
	return &jsonschema.Schema{Not: &jsonschema.Schema{}}
}

// obj builds a strict object schema with additionalProperties disabled (S08).
func obj(props map[string]*jsonschema.Schema, required ...string) *jsonschema.Schema {
	return &jsonschema.Schema{
		Type:                 "object",
		Properties:           props,
		Required:             required,
		AdditionalProperties: falseSchema(),
	}
}

func strP(desc string) *jsonschema.Schema {
	return &jsonschema.Schema{Type: "string", Description: desc}
}

func strEnumP(desc string, vals ...string) *jsonschema.Schema {
	enum := make([]any, 0, len(vals))
	for _, v := range vals {
		enum = append(enum, v)
	}
	return &jsonschema.Schema{Type: "string", Description: desc, Enum: enum}
}

func intP(desc string) *jsonschema.Schema {
	return &jsonschema.Schema{Type: "integer", Description: desc}
}

func arrP(desc string, items *jsonschema.Schema) *jsonschema.Schema {
	return &jsonschema.Schema{Type: "array", Description: desc, Items: items}
}

// envP builds a strict object schema for an env map: any string key maps to a
// string value. The additionalProperties pointer is a fresh instance per call so
// the schema stays a tree for client-side resolution (S08). NUL/newline keys
// and values are rejected by the handler, not the schema.
func envP(desc string) *jsonschema.Schema {
	return &jsonschema.Schema{
		Type:                 "object",
		Description:          desc,
		AdditionalProperties: &jsonschema.Schema{Type: "string"},
	}
}

// objectOutput builds an object-rooted output schema (S09). It is intentionally
// permissive about additional properties because the output is generated by the
// server, not the client.
func objectOutput() *jsonschema.Schema {
	return &jsonschema.Schema{Type: "object"}
}
